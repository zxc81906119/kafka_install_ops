#!/usr/bin/env bash
# cpnode agent for restricted sudo (SUDO_MODE=restricted).
#   cpctl agent build                 -> $STATE_DIR/agent/cpnode (node function bundle + node/cpnode.main), its version
#   cpctl agent install [--restrict]  -> agent + /etc/cpctl/cpnode.conf on every host; --restrict also replaces the
#                                        installer account's sudoers with "cpnode only" (needs full sudo ONE last time)
#   cpctl agent status                -> agent version and sudo mode per host
# After --restrict, cpctl can no longer replace the agent itself: a new agent version (every cpctl upgrade that
# changes node code) is installed by a privileged administrator - that is the point of the restriction.
[[ -n ${_LIB_AGENT_LOADED:-} ]] && return 0
_LIB_AGENT_LOADED=1

readonly AGENT_PATH=/usr/local/libexec/cpctl/cpnode AGENT_CONF=/etc/cpctl/cpnode.conf
AGENT_DIR="$STATE_DIR/agent"

# agent::_body -> what the agent executes (its version is the sha256 of this)
agent::_body() { remote::_bundle; cat "$CPCTL_HOME/node/cpnode.main"; }
agent::version() { agent::_body | sha256sum | cut -c1-16; }

agent::build() {
  local v out=$AGENT_DIR/cpnode
  v=$(agent::version)
  install -d -m 0750 "$AGENT_DIR"
  {
    printf '#!/usr/bin/env bash\n# cpnode %s - generated by cpctl agent build; do not edit (the version is a hash of the code)\n' "$v"
    printf 'set -Eeuo pipefail\numask 022\nreadonly CPNODE_VERSION=%s\n' "$v"
    agent::_body
  } >"$out.new"
  bash -n "$out.new" || core::die "generated agent does not parse"
  mv -f "$out.new" "$out"
  # what an administrator installs on every host besides the agent (restricted mode: cpctl cannot do it itself)
  agent::conf "$AGENT_DIR/cpnode.conf"
  agent::sudoers "$AGENT_DIR/sudoers-$SSH_USER"
  chmod 0750 "$out"
  log::info "agent $out version $v ($(wc -l <"$out") lines)"
}

# agent::hosts -> every host cpctl manages over ssh
agent::hosts() {
  { inv::all_hosts; inv::hosts controller_spare; inv::hosts jump; } | awk 'NF && !seen[$0]++'
}

# agent::paths -> the write allowlist (conf/cpnode.paths: one glob per line, # comments), space separated
agent::paths() {
  {
    sed 's/#.*//' "$CONF_DIR/cpnode.paths"
    # OP menu: ssh keys of its fixed accounts (names come from the inventory)
    if [[ ${OPMENU:-off} == on ]]; then
      local u
      for u in $OPMENU_OS_USER $OPMENU_NODE_USER; do printf '/home/%s/.ssh /home/%s/.ssh/*\n' "$u" "$u"; done
    fi
  } | tr -s ' \t\n' ' ' | sed 's/^ //; s/ $//'
}

# agent::conf <out>
agent::conf() {
  {
    printf '# Managed by cpctl - policy of the cpnode agent (root:root 0644; ignored if anyone else can write it)\n'
    printf 'CPNODE_ENFORCE=%s\n' "${SUDO_AGENT_ENFORCE:-on}"
    printf 'CPNODE_WRITE_PATHS="%s"\n' "$(agent::paths)"
    printf 'CPNODE_SUDOERS_USERS="%s"\n' "${OPMENU_OS_USER:-} ${OPMENU_NODE_USER:-}"
    printf 'CPNODE_TEST_FUNCTIONS=%s\n' "$([[ $PROFILE == poc ]] && echo 1 || echo 0)"
  } >"$1"
}

# agent::sudoers <out> -> the installer account may run the agent as root, without arguments, nothing else
agent::sudoers() {
  cat >"$1" <<EOF
# Managed by cpctl - installer account, RESTRICTED: the cpnode agent is the only privileged program.
# The call arrives on stdin (sudo logs no arguments, so no secrets); the agent logs every call to /var/log/cpnode.log.
Defaults:$SSH_USER !requiretty
Defaults:$SSH_USER logfile=/var/log/sudo-$SSH_USER.log
$SSH_USER ALL=(root) NOPASSWD: $AGENT_PATH ""
EOF
}

agent::install() {
  local restrict=0 h t s
  [[ ${1:-} == --restrict ]] && restrict=1
  # the agent itself can only be installed with full sudo (or by an administrator, see the header)
  export CPCTL_SUDO_FULL=1
  agent::build
  t=$(render::tmp)
  agent::conf "$t"
  s=$(render::tmp)
  agent::sudoers "$s"
  /usr/sbin/visudo -cqf "$s" || core::die "$E_PRECHECK" "generated sudoers does not validate"
  for h in $(agent::hosts); do
    remote::apply "$h" ensure::dir /usr/local/libexec/cpctl root root 0755
    remote::put "$h" "$AGENT_DIR/cpnode" "$AGENT_PATH" root root 0755
    remote::apply "$h" ensure::dir /etc/cpctl root root 0755
    remote::put "$h" "$t" "$AGENT_CONF" root root 0644
    if ((restrict)); then
      remote::put "$h" "$s" "/etc/sudoers.d/$SSH_USER" root root 0440
      log::changed "[$h] $SSH_USER: sudo restricted to $AGENT_PATH"
    fi
  done
  rm -f "$t" "$s"
  ((restrict)) && log::warn "set SUDO_MODE=restricted in conf/inventory.env - full sudo is gone on every host"
  return 0
}

agent::status() {
  local h want have mode rc=0
  want=$(agent::version)
  for h in $(agent::hosts); do
    have=$(printf '%s\0' 0 0 --version | remote::exec "$h" "sudo -n $AGENT_PATH" 2>/dev/null) || have=""
    mode=$(remote::exec "$h" "sudo -n -l 2>/dev/null | grep -c 'NOPASSWD: ALL'" 2>/dev/null || true)
    [[ $mode == 0 ]] && mode=restricted || mode=full
    if [[ $have == "$want" ]]; then log::ok "[$h] agent $have (current), sudo $mode"
    else log::warn "[$h] agent ${have:-missing}, cpctl expects $want, sudo $mode"; rc=2; fi
  done
  return "$rc"
}

agent::main() {
  local sub=${1:-}; shift || true
  case $sub in
    build) agent::build ;;
    install) agent::install "$@" ;;
    status) agent::status ;;
    *) core::die "$E_USAGE" "usage: cpctl agent build|install [--restrict]|status" ;;
  esac
}
